// Reads every .claude/skills/*/SKILL.md and writes site/skills.js for the skills site.
// No dependencies. Vercel runs it on every deploy (see vercel.json); run it locally with
//   node scripts/build-site.mjs
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const skillsDir = join(root, ".claude", "skills");

const field = (fm, key) => {
  const m = fm.match(new RegExp(`^${key}:\\s*(.+)$`, "m"));
  return m ? m[1].trim().replace(/^["']|["']$/g, "") : "";
};

const skills = readdirSync(skillsDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(skillsDir, d.name, "SKILL.md")))
  .map((d) => {
    const text = readFileSync(join(skillsDir, d.name, "SKILL.md"), "utf8");
    const fm = (text.match(/^---\n([\s\S]*?)\n---/) || [, ""])[1];
    const description = field(fm, "description");
    // "What it does. ... Use when ..." -> the summary is the part before "Use when"
    const [what] = description.split(/\s+Use (?:when|after|for)\b/);
    // Cards show the first sentence only
    const summary = (what.match(/^.*?[.!?](?=\s|$)/) || [what])[0];
    const triggers = [...description.matchAll(/"([^"]{3,60})"/g)].map((m) => m[1]).slice(0, 4);
    return { name: field(fm, "name") || d.name, summary: summary.trim(), triggers };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

writeFileSync(
  join(root, "site", "skills.js"),
  "// Generated by scripts/build-site.mjs. Don't edit by hand.\nwindow.SKILLS = " +
    JSON.stringify(skills, null, 2) +
    ";\n"
);
console.log(`site/skills.js: ${skills.length} skills`);
